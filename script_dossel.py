import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files
import pandas as pd

print("Selecione as fotos do dossel para medir a passagem de luz:")
uploaded = files.upload()

resultados_luz = {}

for nome_arquivo in uploaded.keys():
    print(f"\nAnalisando: {nome_arquivo}")

    img = cv2.imread(nome_arquivo)
    if img is None: continue

    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

    # 1. Extração do Canal Azul
    canal_azul = img[:, :, 0]

    # ====================================================================
    # 2. BINARIZAÇÃO COM AJUSTE DE SENSIBILIDADE (ONDE A MUDANÇA OCORRE)
    # ====================================================================

    # Passo A: Deixa o Otsu descobrir o melhor valor de corte automaticamente
    limiar_otsu, _ = cv2.threshold(canal_azul, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)


    # Se os galhos ainda sumirem, aumente para 30 ou 40. Se a máscara ficar muito preta, reduza para 10.
    offset = 30
    novo_limiar = limiar_otsu + offset


    _, mascara_luz = cv2.threshold(canal_azul, novo_limiar, 255, cv2.THRESH_BINARY)

    # ====================================================================

    # 3. Cálculo da Passagem de Luz
    pixels_luz = cv2.countNonZero(mascara_luz)
    pixels_totais = img.shape[0] * img.shape[1]
    porcentagem_luz = (pixels_luz / pixels_totais) * 100

    resultados_luz[nome_arquivo] = porcentagem_luz

    # Visualização
    plt.figure(figsize=(12, 6))

    plt.subplot(1, 2, 1)
    plt.imshow(img_rgb)
    plt.title('Imagem Original')
    plt.axis('off')

    plt.subplot(1, 2, 2)
    plt.imshow(mascara_luz, cmap='gray')
    plt.title(f'Passagem de Luz: {porcentagem_luz:.2f}%')
    plt.axis('off')

    plt.tight_layout()
    plt.show()

# Resumo Final
print("\nRESUMO DA PASSAGEM DE LUZ")
tabela_luz = pd.DataFrame(list(resultados_luz.items()), columns=['Arquivo', 'Luz_Passante_Pct'])
print(tabela_luz)

